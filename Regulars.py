# Задание No3. Валидация российского ИНН физического лица (12 цифр)

print('\nЗадание No3.')

def validate_inn(inn):
    pattern = r'^\d{12}$'
    return bool(re.findall(pattern, str(inn)))

print(f'123456789012 = {validate_inn("123456789012")}')
print(f'12345678901 = {validate_inn("12345678901")}')
print(f'123456f = {validate_inn("123456f")}')
print(f'"" = {validate_inn("")}')




